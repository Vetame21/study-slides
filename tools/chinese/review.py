def P(page, n, sentence, answers):
    """One pinyin → 汉字 sentence. answers = the 汉字 for each blank, in order."""
    blanks = len(answers)
    hint = ("", "") if blanks == 1 else (f" ({blanks} blanks)", f" ({blanks} titik)")
    return F(f"p. {page} · {n}", (f"Write the 汉字{hint[0]}: {sentence}", f"Tulis 汉字{hint[1]}: {sentence}"),
             ["".join(answers)], (" / ".join(answers), " / ".join(answers)))


